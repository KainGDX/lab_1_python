import pandas as pd
import matplotlib.pyplot as plt

#создаем DataFrame с пропусками и выбросами
data = {
    'Товар': ['Яблоки', 'Груши', 'Бананы', 'Апельсины', 'Яблоки'],
    'Цена': [50, 70, None, 90, 60],
    'Количество': [100, -5, 200, 150, 5000]
}
df = pd.DataFrame(data)

#заполняем пропуски медианным значением
df['Цена'] = df['Цена'].fillna(df['Цена'].median())

#удаляем выбросы в количестве
df = df[(df['Количество'] >= 1) & (df['Количество'] <= 1000)]

#считаем общую стоимость
df['Общая_стоимость'] = df['Цена'] * df['Количество']

#группируем по товарам и считаем выручку
revenue = df.groupby('Товар')['Общая_стоимость'].sum()

#строим график
revenue.plot(kind='bar')
plt.title('Выручка по товарам')
plt.ylabel('Выручка')
plt.show()